import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';

const root=fileURLToPath(new URL('../',import.meta.url));
const toolRoot=process.env.GYM_GLTF_TOOLS;
const sourceDir=process.argv[2];
if(!toolRoot||!sourceDir)throw new Error('Usage: GYM_GLTF_TOOLS=/path/to/node_modules node scripts/import-detailed-gym.mjs /path/to/original-glbs');
const {NodeIO}=await import(pathToFileURL(path.join(toolRoot,'@gltf-transform/core/dist/index.js')));
const {ALL_EXTENSIONS}=await import(pathToFileURL(path.join(toolRoot,'@gltf-transform/extensions/dist/index.js')));
const {center,flatten,join,weld,simplify,prune,dedup,getBounds}=await import(pathToFileURL(path.join(toolRoot,'@gltf-transform/functions/dist/index.js')));
const {MeshoptSimplifier}=await import(pathToFileURL(path.join(toolRoot,'meshoptimizer/index.module.js')));
await MeshoptSimplifier.ready;
const {default:sharp}=await import(pathToFileURL(path.join(toolRoot,'sharp/lib/index.js')));
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS);
const selection=JSON.parse(await fs.readFile(path.join(root,'assets/gym-real-sources.json'),'utf8'));
const out=path.join(root,'public/models/gym/precise');await fs.mkdir(out,{recursive:true});
const sha=b=>createHash('sha256').update(b).digest('hex');
const catalog=[],manifest=[];
for(const source of selection){
 const original=await fs.readFile(path.join(sourceDir,source.id+'.glb'));
 if(sha(original)!==source.sourceSha256)throw new Error(source.id+': source hash mismatch');
 const doc=await io.readBinary(original);
 for(const extension of doc.getRoot().listExtensionsUsed())extension.dispose();
 const scene=doc.getRoot().getDefaultScene();
 const rotated=doc.createNode('Metre layout orientation').setRotation([0,Math.SQRT1_2,0,Math.SQRT1_2]);
 for(const child of scene.listChildren())rotated.addChild(child);
 scene.addChild(rotated);
 await doc.transform(flatten(),join({keepNamed:false}),weld(),simplify({simplifier:MeshoptSimplifier,ratio:0.8,error:0.0005}),dedup(),prune(),center({pivot:'below'}));
 for(const texture of doc.getRoot().listTextures()){
  const image=texture.getImage();if(!image)continue;
  texture.setImage(await sharp(Buffer.from(image)).resize(512,512,{fit:'inside',withoutEnlargement:true}).png({compressionLevel:9}).toBuffer()).setMimeType('image/png');
 }
 const bounds=getBounds(scene);const size=bounds.max.map((v,i)=>v-bounds.min[i]);
 if(size.some(n=>!Number.isFinite(n)||n<=0||n>4))throw new Error(source.id+': invalid bounds');
 const dimensions={length_m:Math.ceil(size[0]*1000)/1000,width_m:Math.ceil(size[2]*1000)/1000,height_m:Math.ceil(size[1]*1000)/1000};
 let triangles=0,drawCalls=0;
 for(const mesh of doc.getRoot().listMeshes())for(const primitive of mesh.listPrimitives()){
  drawCalls++;triangles+=(primitive.getIndices()?.getCount()??primitive.getAttribute('POSITION').getCount())/3;
 }
 const bytes=await io.writeBinary(doc);const url='/models/gym/precise/'+source.id+'.glb';
 await fs.writeFile(path.join(root,'public',url),bytes);
 const asset={url,sourceUrl:source.sourceUrl,author:source.author,license:source.license,licenseUrl:source.licenseUrl};
 catalog.push({id:source.id,name:source.name,zone:source.zone,...dimensions,price_eur:source.price_eur,label:source.name,asset});
 manifest.push({...source,...dimensions,url,glbBytes:bytes.length,glbSha256:sha(bytes),triangles,drawCalls,bounds,transforms:['Y-up retained; rotate Y +90 degrees so length is X','centre X/Z and place floor at Y=0; no scaling','flatten/join by source materials; weld; simplify 80%, max relative error0.0005','embedded maps resized to at most512px, PNG, no runtime external requests','remove optional multilayer material extensions for economical standard PBR; retain core materials and embedded maps'],priceNote:'Indicative planning allowance, not a manufacturer quotation.'});
 console.log(source.id,bytes.length,triangles+' triangles',drawCalls+' draws',JSON.stringify(dimensions));
}
await fs.writeFile(path.join(out,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await fs.writeFile(path.join(out,'LICENSE.txt'),'Detailed original models by Innerscene. CC0 1.0. Source pages, original hashes and transformations are recorded in manifest.json. Generic, unbranded visualization models; not manufacturer-certified DHZ assets.\nhttps://www.innerscene.com/tools/library/terms\nhttps://creativecommons.org/publicdomain/zero/1.0/\n');
const types=`export interface ImportedGymModel { id:string; name:string; zone:string; length_m:number; width_m:number; height_m:number; price_eur:number; label:string; asset:{url:string;cadUrl?:string;sourceUrl:string;author:string;license:string;licenseUrl:string} }\n`;
await fs.writeFile(path.join(root,'src/lib/gym-real-equipment.ts'),`// Generated by scripts/import-detailed-gym.mjs.\n${types}export const REAL_EQUIPMENT:ImportedGymModel[] = ${JSON.stringify(catalog,null,2)};\n`);
const dictPath=path.join(root,'src/i18n/ui.en.json');const dict=JSON.parse(await fs.readFile(dictPath,'utf8'));
for(const source of selection)dict[source.name]=source.nameEn;
await fs.writeFile(dictPath,JSON.stringify(dict,null,2)+'\n');
